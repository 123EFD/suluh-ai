def ingest_c_programming_dataset(conn: sqlite3.Connection, target_count: int = 150):
    cur = conn.cursor()
    print(f"Streaming verified C Programming Q&A from Mxode/StackOverflow-QA-C-Language-40k...")
    try:
        from datasets import load_dataset
        ds = load_dataset("Mxode/StackOverflow-QA-C-Language-40k", split="train", streaming=True)
    except Exception as e:
        print(f"Error loading Hugging Face dataset: {e}")
        return

    count = 0
    for row in ds:
        q = row.get("question", "").strip()
        a = row.get("answer", "").strip()

        # Quality filters for academic substance
        if len(q) < 80 or len(q) > 900 or len(a) < 150 or len(a) > 1400:
            continue
        if "homework" in q.lower() or "pls help" in q.lower():
            continue

        # Format clean PYQ item
        pyq_content = f"**Question:**\n{q}\n\n**Solution & Conceptual Rationale:**\n{a}\n\n**Academic Tip:** In C systems programming, always verify pointer boundary constraints, null termination, and memory ownership lifecycle."
        cur.execute(
            "INSERT INTO micro_resources (topic, type, content, duration_min, cognitive_load) VALUES (?, ?, ?, ?, ?)",
            ("Programming", "pyq_solution", pyq_content, 10, 4)
        )

        # Generate a concise Flashcard from the question title/first line
        first_q_line = q.split("\n")[0].strip()
        if len(first_q_line) > 15:
            fc_front = f"In C programming, {first_q_line}"
            # Extract first substantive paragraph of answer
            ans_paragraphs = [p.strip() for p in a.split("\n\n") if len(p.strip()) > 30]
            fc_back = ans_paragraphs[0] if ans_paragraphs else a[:300]
            fc_content = f"**Front:** {fc_front}\n**Back:** {fc_back}\n**Reference:** Kernighan & Ritchie - The C Programming Language"
